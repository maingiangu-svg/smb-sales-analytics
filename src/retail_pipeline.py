"""Prepare the observed Sample Superstore transactions for retail analysis.

The original CSV is kept intact. Profit and discount are read from the source;
neither is imputed or generated by this pipeline.
"""

from pathlib import Path
import re
import sqlite3

import numpy as np
import pandas as pd


ROOT = Path(__file__).resolve().parents[1]
RAW_PATH = ROOT / "data" / "superstore_raw.csv"
DB_PATH = ROOT / "data" / "retail.db"
TABLE = "retail_sales"

REQUIRED = {
    "row_id", "order_id", "order_date", "region", "category",
    "sub_category", "sales", "quantity", "discount", "profit",
}


def read_raw(path: Path = RAW_PATH) -> pd.DataFrame:
    # This public copy of Sample Superstore contains Latin-1 product names.
    return pd.read_csv(path, encoding="latin1", dtype={"Postal Code": "string"})


def audit_raw(raw: pd.DataFrame) -> dict:
    return {
        "rows": len(raw),
        "columns": len(raw.columns),
        "missing_cells": int(raw.isna().sum().sum()),
        "missing_by_column": raw.isna().sum().loc[lambda s: s.gt(0)].to_dict(),
        "duplicate_rows": int(raw.duplicated().sum()),
        "duplicate_row_ids": int(raw["Row ID"].duplicated().sum()),
    }


def clean_retail(raw: pd.DataFrame) -> pd.DataFrame:
    df = raw.copy()
    df.columns = [re.sub(r"[^a-z0-9]+", "_", str(c).lower()).strip("_") for c in df.columns]
    missing = REQUIRED - set(df.columns)
    if missing:
        raise ValueError(f"Missing required source columns: {sorted(missing)}")

    df = df.drop_duplicates(subset="row_id", keep="first")
    for col in ("order_date", "ship_date"):
        if col in df:
            df[col] = pd.to_datetime(df[col], format="%m/%d/%Y", errors="coerce")
    for col in ("sales", "profit", "quantity", "discount"):
        df[col] = pd.to_numeric(df[col], errors="coerce")

    valid = (
        df["order_date"].notna()
        & df["row_id"].notna()
        & df["sales"].gt(0)
        & df["quantity"].gt(0)
        & df["discount"].between(0, 1)
        & df["profit"].notna()
        & df["region"].notna()
        & df["category"].notna()
    )
    df = df.loc[valid].copy()
    if df.empty:
        raise ValueError("No valid retail transactions remain after validation")

    df["year"] = df["order_date"].dt.year
    df["month"] = df["order_date"].dt.month
    df["day_of_week"] = df["order_date"].dt.day_name()
    df["profit_margin"] = np.where(df["sales"].gt(0), 100 * df["profit"] / df["sales"], np.nan)
    df["is_loss"] = df["profit"].lt(0)
    df["discount_band"] = pd.cut(
        df["discount"],
        bins=[-0.001, 0, 0.2, 0.4, 0.6, 1],
        labels=["0%", ">0–20%", ">20–40%", ">40–60%", ">60%"],
    ).astype(str)
    return df


def run_pipeline(raw_path: Path = RAW_PATH, db_path: Path = DB_PATH) -> dict:
    raw = read_raw(raw_path)
    audit = audit_raw(raw)
    clean = clean_retail(raw)
    db_path.parent.mkdir(parents=True, exist_ok=True)
    with sqlite3.connect(db_path) as conn:
        clean.to_sql(TABLE, conn, if_exists="replace", index=False)
    audit["clean_rows"] = len(clean)
    audit["removed_rows"] = len(raw) - len(clean)
    return audit


if __name__ == "__main__":
    print(run_pipeline())
